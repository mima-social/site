#!/usr/bin/env python3
"""Render the animation scenes in scenes.py to short videos.

    python3 app-shots/build.py            # the dummy pages the scenes play over
    python3 app-shots/animate.py          # every scene
    python3 app-shots/animate.py <scene>  # one scene

For each scene it writes, in site-assets/app/:

    <scene>.mp4          H.264, no sound, plays everywhere
    <scene>-poster.webp  the still shown before it plays
    <scene>.mp4.json     where it came from, its size and length, and its alt text

How: player.html draws the frame for any time t, headless Chrome screenshots
one frame per 1/fps second, and ffmpeg joins them. Needs Google Chrome, ffmpeg
and cwebp (brew install ffmpeg webp). Standard library only. To watch a scene
before rendering, serve the repo root and open
/app-shots/player.html?scene=<scene>.
"""

import concurrent.futures
import datetime
import functools
import http.server
import json
import os
import pathlib
import shutil
import subprocess
import sys
import tempfile
import threading

HERE = pathlib.Path(__file__).parent
ROOT = HERE.parent
OUT = ROOT / "site-assets" / "app"
CHROME = os.environ.get("CHROME", "/Applications/Google Chrome.app/Contents/MacOS/Google Chrome")
SCALE = 1.5   # device pixels per CSS px: 960 wide -> 1440, sharp without a heavy file
WORKERS = 6

sys.path.insert(0, str(HERE))
from scenes import SCENES  # noqa: E402


def write_scenes_js():
    """scenes.js is scenes.py as data for player.html; never edit it by hand."""
    (HERE / "scenes.js").write_text(
        "// Generated by app-shots/animate.py from scenes.py. Do not edit.\n"
        f"window.SCENES = {json.dumps(SCENES, indent=2)};\n")


def frame_times(scene):
    """The time in ms of every frame: one per 1/fps second across all steps."""
    total = sum(s["ms"] for s in scene["steps"])
    step = 1000 / scene["fps"]
    return [round(i * step) for i in range(int(total / step))]


def check(name, scene):
    """Fail early, with the reason, on a scene the player could not play."""
    for i, s in enumerate(scene["steps"]):
        if not (HERE / f"{s['view']}.html").exists():
            sys.exit(f"{name}: step {i} names view `{s['view']}`, but app-shots/{s['view']}.html does not exist "
                     "(run app-shots/build.py)")
        if s.get("click") and s["ms"] < 600:
            sys.exit(f"{name}: step {i} clicks but lasts {s['ms']} ms; give it at least 600")


def shoot(url, out, size):
    w, h = size
    subprocess.run([CHROME, "--headless=new", "--disable-gpu", "--hide-scrollbars",
                    f"--force-device-scale-factor={SCALE}", "--virtual-time-budget=4000",
                    f"--window-size={w},{h}", f"--screenshot={out}", url],
                   check=True, capture_output=True)


def render(name, scene, port):
    check(name, scene)
    times = frame_times(scene)
    base = f"http://localhost:{port}/app-shots/player.html?scene={name}"
    with tempfile.TemporaryDirectory() as tmp:
        tmp = pathlib.Path(tmp)
        with concurrent.futures.ThreadPoolExecutor(WORKERS) as pool:
            list(pool.map(lambda it: shoot(f"{base}&t={it[1]}", tmp / f"f{it[0]:05d}.png", scene["size"]),
                          enumerate(times)))
        mp4 = OUT / f"{name}.mp4"
        # Even dimensions and yuv420p so every browser and phone can play it.
        subprocess.run(["ffmpeg", "-y", "-loglevel", "error", "-framerate", str(scene["fps"]),
                        "-i", str(tmp / "f%05d.png"), "-vf", "scale=trunc(iw/2)*2:trunc(ih/2)*2",
                        "-c:v", "libx264", "-preset", "slow", "-crf", "24", "-pix_fmt", "yuv420p",
                        "-movflags", "+faststart", "-an", str(mp4)], check=True)
        poster_ms = scene.get("poster_ms", times[-1])
        poster = min(range(len(times)), key=lambda i: abs(times[i] - poster_ms))
        subprocess.run(["cwebp", "-quiet", "-q", "88", str(tmp / f"f{poster:05d}.png"),
                        "-o", str(OUT / f"{name}-poster.webp")], check=True)
    w, h = (int(round(x * SCALE / 2)) * 2 for x in scene["size"])
    (OUT / f"{name}.mp4.json").write_text(json.dumps({
        "prompt": f"Origin: rendered by app-shots/animate.py from the scene `{name}` in app-shots/scenes.py, "
                  "played over dummy pages from app-shots/build.py (fictional content; real Mima UI styles "
                  "from mima-social/desktop).",
        "alt": scene["alt"],
        "width": w, "height": h, "seconds": round(len(times) / scene["fps"], 1),
        "createdAt": datetime.datetime.now(datetime.timezone.utc).strftime("%Y-%m-%dT%H:%M:%S.000Z"),
    }, indent=2) + "\n")
    print(f"rendered site-assets/app/{name}.mp4 ({len(times)} frames, {mp4.stat().st_size // 1024} KB)")


class QuietHandler(http.server.SimpleHTTPRequestHandler):
    def log_message(self, *args):
        pass


def main(argv):
    names = argv or list(SCENES)
    for n in names:
        if n not in SCENES:
            sys.exit(f"No scene `{n}` in app-shots/scenes.py. Scenes: {', '.join(SCENES)}")
    for tool in (CHROME, "ffmpeg", "cwebp"):
        if not shutil.which(tool):
            sys.exit(f"animate.py needs {tool}")
    write_scenes_js()
    handler = functools.partial(QuietHandler, directory=str(ROOT))
    server = http.server.ThreadingHTTPServer(("127.0.0.1", 0), handler)
    threading.Thread(target=server.serve_forever, daemon=True).start()
    try:
        for n in names:
            render(n, SCENES[n], server.server_address[1])
    finally:
        server.shutdown()


if __name__ == "__main__":
    main(sys.argv[1:])
